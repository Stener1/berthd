// writeClaudeFile writes a Claude Code transcript of lines (JSON objects)
// for conversation sid in dir, as Claude Code keeps it under claudeHome.
func writeClaudeFile(t *testing.T, claudeHome, dir, sid string, lines ...map[string]any) string {
	t.Helper()
	folder := claudeFolders(claudeHome, dir)[0]
	if err := os.MkdirAll(folder, 0o700); err != nil {
		t.Fatal(err)
	}
	var b strings.Builder
	for _, l := range lines {
		raw, _ := json.Marshal(l)
		b.Write(raw)
		b.WriteByte('\n')
	}
	path := filepath.Join(folder, sid+".jsonl")
	if err := os.WriteFile(path, []byte(b.String()), 0o600); err != nil {
		t.Fatal(err)
	}
	return path
}

func userLine(sid, text string, extra map[string]any) map[string]any {
	l := map[string]any{"type": "user", "sessionId": sid, "uuid": "u-" + text, "timestamp": "2026-10-13T12:00:00Z", "message": map[string]any{"role": "user", "content": text}}
	for k, v := range extra {
		l[k] = v
	}
	return l
}

func TestClaudesPastConversationsAreListedByTheirTitlesNewestFirst(t *testing.T) {
	home, dir := t.TempDir(), "/home/dev/acme"
	const a, b, c, d = "00000000-0000-4000-8000-00000000000a", "00000000-0000-4000-8000-00000000000b", "00000000-0000-4000-8000-00000000000c", "00000000-0000-4000-8000-00000000000d"
	// Named by the person, then by Claude: the person's name wins.
	pa := writeClaudeFile(t, home, dir, a,
		userLine(a, "<command-name>/clear</command-name>", nil),
		userLine(a, "Caveat: the messages below were generated by the user while running local commands.", map[string]any{"isMeta": true}),
		userLine(a, "Fix the flaky checkout test\nIt fails one run in ten.", nil),
		map[string]any{"type": "ai-title", "sessionId": a, "aiTitle": "Fix flaky checkout test"},
		map[string]any{"type": "custom-title", "sessionId": a, "customTitle": "checkout flake"})
	// Named by Claude only.
	pb := writeClaudeFile(t, home, dir, b,
		userLine(b, "Add a dark theme", nil),
		map[string]any{"type": "ai-title", "sessionId": b, "aiTitle": "Add dark theme"})
	// Its first prompt, cut to a title.
	pc := writeClaudeFile(t, home, dir, c, userLine(c, "Why is the build slow?\nIt takes ten minutes.", nil))
	// Never prompted: not one to carry on.
	writeClaudeFile(t, home, dir, d, map[string]any{"type": "permission-mode", "sessionId": d, "permissionMode": "default"})
	// Another folder's conversation isn't this one's.
	writeClaudeFile(t, home, "/home/dev/other", "00000000-0000-4000-8000-0000000000ff", userLine("x", "elsewhere", nil))
	now := time.Now()
	for i, p := range []string{pa, pb, pc} {
		at := now.Add(-time.Duration(3-i) * time.Hour)
		os.Chtimes(p, at, at)
	}

	got := claudePast(home, dir, 10)
	var titles []string
	for _, p := range got {
		titles = append(titles, p.ID[len(p.ID)-1:]+" "+p.Title)
	}
	want := "c Why is the build slow?|b Add dark theme|a checkout flake"
	if strings.Join(titles, "|") != want {
		t.Fatalf("listed %q, want %q", strings.Join(titles, "|"), want)
	}
	if got := claudePast(home, dir, 2); len(got) != 2 {
		t.Fatalf("limited to 2, listed %d", len(got))
	}
}

func TestAStructuredClaudeChatCarriesOnOneOfClaudesPastConversations(t *testing.T) {
	if _, err := exec.LookPath("python3"); err != nil {
		t.Skip("the stand-in Claude needs python3")
	}
	bin := t.TempDir()
	os.WriteFile(filepath.Join(bin, "claude"), []byte(fakeStreamClaude), 0o755)
	t.Setenv("PATH", bin+string(os.PathListSeparator)+os.Getenv("PATH"))
	claudeHome := t.TempDir()
	t.Setenv("CLAUDE_CONFIG_DIR", claudeHome)
	exe, _ := os.Executable()
	states := &Turns{}
	c, bus := servedBox(t, func(b *Box) {
		b.Turns = states
		b.ConversationsDir = conversationsDir(t)
		b.AgentHost = []string{"env", "BERTH_TEST_AGENT_HOST=1", exe}
	})
	states.Attach(bus)
	repo := gitRepo(t)
	real, _ := filepath.EvalSymlinks(repo)
	// A conversation had in Claude Code's own terminal, before.
	const past = "00000000-0000-4000-8000-0000000000p1"
	writeClaudeFile(t, claudeHome, real, past,
		userLine(past, "plan the release", nil),
		map[string]any{"type": "assistant", "sessionId": past, "uuid": "a-1", "timestamp": "2026-10-13T12:00:01Z", "message": map[string]any{"id": "msg_p", "role": "assistant", "content": []any{map[string]any{"type": "text", "text": "Here is the release plan."}}}},
		map[string]any{"type": "custom-title", "sessionId": past, "customTitle": "release plan"})

	call(t, c, "POST", "/v1/locations", "", map[string]string{"name": "acme", "path": repo}, nil)
	var sess Session
	call(t, c, "POST", "/v1/sessions", "", map[string]any{"location": "acme", "agent": "claude", "driver": "claude", "prompt": "hello"}, &sess)
	t.Cleanup(func() { call(t, c, "DELETE", "/v1/sessions/"+sess.Name, "", nil, nil) })
	until := func(what string, ok func() bool) {
		t.Helper()
		deadline := time.Now().Add(15 * time.Second)
		for !ok() {
			if time.Now().After(deadline) {
				t.Fatalf("%s never happened", what)
			}
			time.Sleep(50 * time.Millisecond)
		}
	}
	said := func(text string) func() bool {
		return func() bool {
			var res transcript.Result
			call(t, c, "GET", "/v1/sessions/"+sess.Name+"/transcript?since=0", "", nil, &res)
			for _, it := range res.Items {
				if strings.Contains(it.Text, text) {
					return true
				}
			}
			return false
		}
	}
	until("the first reply", said("echo: hello"))
	until("its turn's end", func() bool { st, _ := states.State(sess.Name); return st.State == "finished" })

	// The stand-in leaves its own file empty; Claude Code writes the prompt.
	const own = "00000000-0000-4000-8000-0000000000c1"
	writeClaudeFile(t, claudeHome, real, own, userLine(own, "hello", nil))

	// The chat's /resume: what Claude has had in this folder, this chat's
	// own conversation among it.
	var list PastSessions
	if status := call(t, c, "GET", "/v1/sessions/"+sess.Name+"/past", "", nil, &list); status != 200 || list.Agent != "claude" {
		t.Fatalf("past: %d %+v", status, list)
	}
	found := map[string]PastSession{}
	for _, p := range list.Sessions {
		found[p.ID] = p
	}
	if p := found[past]; p.Title != "release plan" || p.Current {
		t.Fatalf("the past conversation is %+v in %+v", p, list.Sessions)
	}
	if p := found[own]; !p.Current || p.Title != "hello" {
		t.Fatalf("the chat's own conversation is %+v in %+v", p, list.Sessions)
	}
	var cat CommandCatalog
	call(t, c, "GET", "/v1/sessions/"+sess.Name+"/commands", "", nil, &cat)
	for _, cmd := range cat.Commands {
		if cmd.Name == "/resume" && (!cmd.App || cmd.Screen || !slices.Contains(cmd.Aliases, "/continue")) {
			t.Fatalf("a structured chat's /resume is %+v", cmd)
		}
	}

	if status := call(t, c, "POST", "/v1/sessions/"+sess.Name+"/resume", "", map[string]string{"agent_session_id": "00000000-0000-4000-8000-000000000404"}, nil); status != http.StatusNotFound {
		t.Fatalf("one Claude doesn't have: %d", status)
	}
	if status := call(t, c, "POST", "/v1/sessions/"+sess.Name+"/resume", "", map[string]string{"agent_session_id": "../etc"}, nil); status != http.StatusBadRequest {
		t.Fatalf("a path for an id: %d", status)
	}
	var resumed Session
	if status := call(t, c, "POST", "/v1/sessions/"+sess.Name+"/resume", "", map[string]string{"agent_session_id": past}, &resumed); status != 200 || resumed.Exited || resumed.Driver != DriverClaude || resumed.Title != "release plan" {
		t.Fatalf("resume %s: %d %+v", past, status, resumed)
	}
	// What was said in the terminal shows, and the chat carries on from it.
	until("the past conversation in the chat", said("Here is the release plan."))
	if said("echo: hello")() {
		t.Fatal("the conversation it left still shows")
	}
	call(t, c, "POST", "/v1/sessions/"+sess.Name+"/send", "", map[string]any{"text": "ship it", "when": "now"}, nil)
	until("a reply in the carried-on conversation", said("echo: ship it"))

	// The one it left stays, to be resumed later.
	var convs []Conversation
	call(t, c, "GET", "/v1/conversations?path="+repo, "", nil, &convs)
	if len(convs) != 2 {
		t.Fatalf("conversations = %+v", convs)
	}
	for _, cv := range convs {
		if cv.Title == "hello" && cv.Live {
			t.Fatalf("the conversation it left is still live: %+v", cv)
		}
	}
}

func TestAnACPChatCarriesOnOneOfItsAgentsPastSessions(t *testing.T) {
	if _, err := exec.LookPath("python3"); err != nil {
		t.Skip("the stand-in agent needs python3")
	}
	bin := t.TempDir()
	os.WriteFile(filepath.Join(bin, "opencode"), []byte(fakeACPAgent), 0o755)
	t.Setenv("PATH", bin+string(os.PathListSeparator)+os.Getenv("PATH"))
	exe, _ := os.Executable()
	states := &Turns{}
	c, bus := servedBox(t, func(b *Box) {
		b.Turns = states
		b.ConversationsDir = conversationsDir(t)
		b.AgentHost = []string{"env", "BERTH_TEST_AGENT_HOST=1", exe}
	})
	states.Attach(bus)
	repo := gitRepo(t)
	call(t, c, "POST", "/v1/locations", "", map[string]string{"name": "acme", "path": repo}, nil)
	var sess Session
	call(t, c, "POST", "/v1/sessions", "", map[string]any{"location": "acme", "agent": "opencode", "driver": "acp", "prompt": "hello"}, &sess)
	t.Cleanup(func() { call(t, c, "DELETE", "/v1/sessions/"+sess.Name, "", nil, nil) })
	texts := func() []string {
		var res transcript.Result
		call(t, c, "GET", "/v1/sessions/"+sess.Name+"/transcript?since=0", "", nil, &res)
		var out []string
		for _, it := range res.Items {
			out = append(out, it.Kind+":"+strings.TrimSpace(it.Text))
		}
		return out
	}
	until := func(what string, ok func() bool) {
		t.Helper()
		deadline := time.Now().Add(15 * time.Second)
		for !ok() {
			if time.Now().After(deadline) {
				t.Fatalf("%s never happened: %q", what, texts())
			}
			time.Sleep(50 * time.Millisecond)
		}
	}
	said := func(text string) func() bool {
		return func() bool { return slices.Contains(texts(), text) }
	}
	until("the first reply", said("text:echo: hello (build)"))
	until("its turn's end", func() bool { st, _ := states.State(sess.Name); return st.State == "finished" })

	var list PastSessions
	if status := call(t, c, "GET", "/v1/sessions/"+sess.Name+"/past", "", nil, &list); status != 200 {
		t.Fatalf("past: %d %+v", status, list)
	}
	var got []string
	for _, p := range list.Sessions {
		s := p.ID + " " + p.Title
		if p.Current {
			s += " (current)"
		}
		got = append(got, s)
	}
	if strings.Join(got, "|") != "ses_fake1 This one (current)|ses_old Old work" {
		t.Fatalf("past = %q (%s)", got, list.Note)
	}

	if status := call(t, c, "POST", "/v1/sessions/"+sess.Name+"/resume", "", map[string]string{"agent_session_id": "ses_old"}, nil); status != 200 {
		t.Fatalf("resume: %d", status)
	}
	// Loaded, it replays what was said: the chat shows it, once.
	until("the replayed conversation", func() bool {
		return strings.Join(texts(), "|") == "user:earlier question|text:earlier answer"
	})
	call(t, c, "POST", "/v1/sessions/"+sess.Name+"/send", "", map[string]any{"text": "go on", "when": "now"}, nil)
	until("a reply in the carried-on session", said("text:echo: go on (build)"))
	if st, _ := states.State(sess.Name); st.AgentSessionID != "ses_old" {
		t.Fatalf("it carries on %q", st.AgentSessionID)
	}
}
