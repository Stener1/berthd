package postgres

import (
	"context"
	"encoding/json"
	"strconv"

	"github.com/jackc/pgx/v5/pgconn"

	"github.com/cosscom/shipyard/internal/database"
)

// The relations the editor lists and opens: tables (plain, partitioned and
// foreign), views and materialized views. And what is nobody's own schema.
const (
	relkinds = `('r','p','f','v','m')`
	ownData  = `n.nspname <> 'information_schema' AND n.nspname !~ '^pg_'`
	// estimate is how many rows a relation has, without counting them: the
	// planner's number from the last ANALYZE or VACUUM. A table that has
	// never had one (a small one, which autovacuum leaves alone) has -1
	// there, and gets what the statistics collector has counted going in
	// and out instead.
	estimate = `CASE WHEN c.relkind = 'v' THEN 0
	                 WHEN c.reltuples >= 0 THEN c.reltuples::bigint
	                 ELSE coalesce(pg_stat_get_live_tuples(c.oid), 0) END`
)

func kindOf(relkind string) string {
	switch relkind {
	case "v":
		return database.KindView
	case "m":
		return database.KindMaterializedView
	}
	return database.KindTable
}

// names reads a JSON list of names the server made.
func names(text string) []string {
	out := []string{}
	if text != "" {
		json.Unmarshal([]byte(text), &out)
	}
	return out
}

func (c *conn) Schema(ctx context.Context) (*database.Schema, error) {
	out := &database.Schema{Schemas: []database.SchemaInfo{}}
	err := c.within(ctx, false, true, c.timeout, func(ctx context.Context, pc *pgconn.PgConn) error {
		schemas, err := read(ctx, pc, `SELECT n.nspname FROM pg_namespace n WHERE `+ownData+` ORDER BY 1`)
		if err != nil {
			return err
		}
		at := map[string]int{}
		for _, row := range schemas {
			at[row[0]] = len(out.Schemas)
			out.Schemas = append(out.Schemas, database.SchemaInfo{Name: row[0], Tables: []database.Table{}})
		}

		rels, err := read(ctx, pc, `SELECT c.oid, n.nspname, c.relname, c.relkind, `+estimate+`
			FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
			WHERE c.relkind IN `+relkinds+` AND `+ownData+`
			ORDER BY n.nspname, c.relname`)
		if err != nil {
			return err
		}
		// Each table by its oid, filled in before it is put in its schema.
		tables := map[string]*database.Table{}
		var order []string
		in := map[string]string{}
		for _, row := range rels {
			rows, _ := strconv.ParseInt(row[4], 10, 64)
			tables[row[0]] = &database.Table{Name: row[2], Kind: kindOf(row[3]), RowsEstimate: rows,
				Columns: []database.TableColumn{}, PrimaryKey: []string{}, Indexes: []database.Index{}, ForeignKeys: []database.ForeignKey{}}
			order = append(order, row[0])
			in[row[0]] = row[1]
		}

		// Read raw: a column with no default has a NULL there, not "".
		cols := pc.ExecParams(ctx, `SELECT a.attrelid, a.attname, format_type(a.atttypid, a.atttypmod), NOT a.attnotnull,
			       CASE WHEN a.attidentity = 'a' THEN 'generated always as identity'
			            WHEN a.attidentity = 'd' THEN 'generated by default as identity'
			            WHEN a.attgenerated <> '' THEN 'generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ')'
			                 || CASE WHEN a.attgenerated = 's' THEN ' stored' ELSE '' END
			            ELSE pg_get_expr(d.adbin, d.adrelid) END
			FROM pg_attribute a
			JOIN pg_class c ON c.oid = a.attrelid JOIN pg_namespace n ON n.oid = c.relnamespace
			LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
			WHERE a.attnum > 0 AND NOT a.attisdropped AND c.relkind IN `+relkinds+` AND `+ownData+`
			ORDER BY a.attrelid, a.attnum`, nil, nil, nil, nil).Read()
		if cols.Err != nil {
			return cols.Err
		}
		for _, row := range cols.Rows {
			t := tables[string(row[0])]
			if t == nil {
				continue
			}
			col := database.TableColumn{Name: string(row[1]), Type: string(row[2]), Nullable: string(row[3]) == "t"}
			if row[4] != nil {
				def := string(row[4])
				col.Default = &def
			}
			t.Columns = append(t.Columns, col)
		}

		indexes, err := read(ctx, pc, `SELECT i.indrelid, ic.relname, i.indisunique, i.indisprimary,
			       (SELECT json_agg(coalesce(a.attname, pg_get_indexdef(i.indexrelid, k.n::int, true)) ORDER BY k.n)
			          FROM unnest(i.indkey::int2[]) WITH ORDINALITY AS k(attnum, n)
			          LEFT JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = k.attnum AND k.attnum > 0
			         WHERE k.n <= i.indnkeyatts)::text
			FROM pg_index i JOIN pg_class ic ON ic.oid = i.indexrelid
			JOIN pg_class c ON c.oid = i.indrelid JOIN pg_namespace n ON n.oid = c.relnamespace
			WHERE c.relkind IN `+relkinds+` AND `+ownData+`
			ORDER BY i.indrelid, i.indisprimary DESC, ic.relname`)
		if err != nil {
			return err
		}
		for _, row := range indexes {
			t := tables[row[0]]
			if t == nil {
				continue
			}
			ix := database.Index{Name: row[1], Columns: names(row[4]), Unique: row[2] == "t"}
			t.Indexes = append(t.Indexes, ix)
			if row[3] == "t" {
				t.PrimaryKey = ix.Columns
				for i := range t.Columns {
					for _, key := range ix.Columns {
						if t.Columns[i].Name == key {
							t.Columns[i].PrimaryKey = true
						}
					}
				}
			}
		}

		fks, err := read(ctx, pc, `SELECT con.conrelid,
			       (SELECT json_agg(a.attname ORDER BY k.n) FROM unnest(con.conkey) WITH ORDINALITY AS k(attnum, n)
			          JOIN pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = k.attnum)::text,
			       fn.nspname, fc.relname,
			       (SELECT json_agg(a.attname ORDER BY k.n) FROM unnest(con.confkey) WITH ORDINALITY AS k(attnum, n)
			          JOIN pg_attribute a ON a.attrelid = con.confrelid AND a.attnum = k.attnum)::text
			FROM pg_constraint con
			JOIN pg_class c ON c.oid = con.conrelid JOIN pg_namespace n ON n.oid = c.relnamespace
			JOIN pg_class fc ON fc.oid = con.confrelid JOIN pg_namespace fn ON fn.oid = fc.relnamespace
			WHERE con.contype = 'f' AND `+ownData+`
			ORDER BY con.conrelid, con.conname`)
		if err != nil {
			return err
		}
		for _, row := range fks {
			if t := tables[row[0]]; t != nil {
				t.ForeignKeys = append(t.ForeignKeys, database.ForeignKey{Columns: names(row[1]),
					RefSchema: row[2], RefTable: row[3], RefColumns: names(row[4])})
			}
		}

		for _, oid := range order {
			if i, ok := at[in[oid]]; ok {
				out.Schemas[i].Tables = append(out.Schemas[i].Tables, *tables[oid])
			}
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	return out, nil
}

// tableInfo is one table as Rows and Edit need it.
type tableInfo struct {
	oid      string
	kind     string
	estimate int64
	cols     []colInfo
	pk       []string
}

type colInfo struct {
	name string
	typ  string
	// base is the type's oid, or for a domain the type under it.
	base uint32
	// typmod is the type's modifier: for char(n), n and four more.
	typmod int
}

func (t *tableInfo) has(column string) bool {
	for _, c := range t.cols {
		if c.name == column {
			return true
		}
	}
	return false
}

// describe looks one table up by its names, which go as parameters.
func describe(ctx context.Context, pc *pgconn.PgConn, schema, table string) (*tableInfo, error) {
	found, err := read(ctx, pc, `SELECT c.oid, c.relkind, `+estimate+`
		FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
		WHERE n.nspname = $1 AND c.relname = $2 AND c.relkind IN `+relkinds, schema, table)
	if err != nil {
		return nil, err
	}
	if len(found) == 0 {
		return nil, database.NotFound("There is no table %s in this database.", quote(schema)+"."+quote(table))
	}
	t := &tableInfo{oid: found[0][0], kind: kindOf(found[0][1]), pk: []string{}}
	t.estimate, _ = strconv.ParseInt(found[0][2], 10, 64)

	cols, err := read(ctx, pc, `SELECT a.attname, format_type(a.atttypid, a.atttypmod),
		       CASE WHEN t.typtype = 'd' THEN t.typbasetype ELSE t.oid END, a.atttypmod
		FROM pg_attribute a JOIN pg_type t ON t.oid = a.atttypid
		WHERE a.attrelid = $1::oid AND a.attnum > 0 AND NOT a.attisdropped
		ORDER BY a.attnum`, t.oid)
	if err != nil {
		return nil, err
	}
	for _, row := range cols {
		base, _ := strconv.ParseUint(row[2], 10, 32)
		typmod, _ := strconv.Atoi(row[3])
		t.cols = append(t.cols, colInfo{name: row[0], typ: row[1], base: uint32(base), typmod: typmod})
	}
	keys, err := read(ctx, pc, `SELECT a.attname
		FROM pg_index i CROSS JOIN LATERAL unnest(i.indkey::int2[]) WITH ORDINALITY AS k(attnum, n)
		JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = k.attnum
		WHERE i.indrelid = $1::oid AND i.indisprimary
		ORDER BY k.n`, t.oid)
	if err != nil {
		return nil, err
	}
	for _, row := range keys {
		t.pk = append(t.pk, row[0])
	}
	return t, nil
}
