export type IconName = keyof typeof icons;

export const iconNames = Object.keys(icons) as IconName[];

export function DynamicIcon({ name, ...props }: LucideProps & { name: IconName }) {
  const Icon = icons[name] ?? PuzzleIcon;
  return <Icon {...props} />;
}
